def mql_quote(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return '"' + escaped + '"'


def write_python_symbols(data: dict[str, Any]) -> None:
    validate_symbol_registry_data(data)
    brokers = {
        broker: dict(sorted(mapping.items()))
        for broker, mapping in sorted(data["brokers"].items())
    }
    canonicals = {
        canonical: dict(sorted(entry.items()))
        for canonical, entry in sorted(data["canonicals"].items())
    }
    lines = [*SYMBOLS_PY_HEADER]
    lines.extend(
        [
            "from __future__ import annotations",
            "",
            "from dataclasses import dataclass",
            "from typing import Final",
            "",
            "",
            "@dataclass(frozen=True)",
            "class RiskProfile:",
            "    max_spread_points: int | None",
            "    max_sl_distance_pct: float",
            "    session_policy: str",
            "",
            "",
            "@dataclass(frozen=True)",
            "class CanonicalSymbol:",
            "    base: str",
            "    quote: str",
            "    group: str",
            "    risk: RiskProfile",
            "",
            "",
            f"REGISTRY_VERSION: Final[int] = {data['version']}",
            "",
            "BROKER_TO_CANONICAL: Final[dict[str, dict[str, str]]] = {",
        ]
    )
    for broker, mapping in brokers.items():
        lines.append(f"    {broker!r}: {{")
        for raw, canonical in mapping.items():
            lines.append(f"        {raw!r}: {canonical!r},")
        lines.append("    },")
    lines.append("}")
    lines.append("")
    lines.append("CANONICALS: Final[dict[str, CanonicalSymbol]] = {")
    for canonical, entry in canonicals.items():
        lines.extend(
            [
                f"    {canonical!r}: CanonicalSymbol(",
                f"        base={entry['base']!r},",
                f"        quote={entry['quote']!r},",
                f"        group={entry['group']!r},",
                "        risk=RiskProfile(",
                f"            max_spread_points={entry['max_spread_points']!r},",
                f"            max_sl_distance_pct={float(entry['max_sl_distance_pct'])!r},",
                f"            session_policy={entry['session_policy']!r},",
                "        ),",
                "    ),",
            ]
        )
    lines.append("}")
    lines.append("")
    atomic_write(PY_OUT_DIR / "symbols.py", "\n".join(lines))


def write_mql5_symbols(data: dict[str, Any]) -> None:
    validate_symbol_registry_data(data)
    broker_items = [
        (broker, raw, canonical)
        for broker, mapping in sorted(data["brokers"].items())
        for raw, canonical in sorted(mapping.items())
    ]
    canonical_items = [
        (canonical, entry) for canonical, entry in sorted(data["canonicals"].items())
    ]
    lines = [*SYMBOLS_MQL5_HEADER]
    lines.extend(
        [
            "#ifndef FARM_SYMBOLS_MQH",
            "#define FARM_SYMBOLS_MQH",
            "",
            "string FarmSymbolCanonical(const string broker, const string raw)",
            "{",
        ]
    )
    for broker, raw, canonical in broker_items:
        lines.append(
            f"   if(broker == {mql_quote(broker)} && raw == {mql_quote(raw)}) "
            f"return {mql_quote(canonical)};"
        )
    lines.extend(["   return \"\";", "}", ""])

    for function, field in [
        ("FarmSymbolBase", "base"),
        ("FarmSymbolQuote", "quote"),
        ("FarmSymbolCorrelationGroup", "group"),
    ]:
        lines.extend([f"string {function}(const string canonical)", "{"])
        for canonical, entry in canonical_items:
            lines.append(
                f"   if(canonical == {mql_quote(canonical)}) "
                f"return {mql_quote(entry[field])};"
            )
        lines.extend(["   return \"\";", "}", ""])

    lines.extend(
        [
            "bool FarmSymbolRisk(const string canonical,",
            "                    int    &out_max_spread_points,",
            "                    double &out_max_sl_distance_pct,",
            "                    string &out_session_policy)",
            "{",
            "   out_max_spread_points = -1;",
            "   out_max_sl_distance_pct = 0.0;",
            "   out_session_policy = \"\";",
        ]
    )
    for canonical, entry in canonical_items:
        spread = -1 if entry["max_spread_points"] is None else int(entry["max_spread_points"])
        lines.extend(
            [
                f"   if(canonical == {mql_quote(canonical)})",
                "   {",
                f"      out_max_spread_points = {spread};",
                f"      out_max_sl_distance_pct = {float(entry['max_sl_distance_pct'])!r};",
                f"      out_session_policy = {mql_quote(entry['session_policy'])};",
                "      return true;",
                "   }",
            ]
        )
    lines.extend(["   return false;", "}", ""])

    lines.extend(["bool FarmSymbolProductionReady(const string canonical)", "{"])
    for canonical, entry in canonical_items:
        ready = "true" if entry["max_spread_points"] is not None else "false"
        lines.append(f"   if(canonical == {mql_quote(canonical)}) return {ready};")
    lines.extend(["   return false;", "}", "", "#endif", ""])
    atomic_write(MQL5_OUT_DIR / "FarmSymbols.mqh", "\n".join(lines))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.parse_args(argv)
    schemas = load_schemas()
    symbols_data = load_symbol_registry_data(SYMBOLS_FILE)
    write_python_models(schemas)
    write_mql5_models(schemas)
    write_python_symbols(symbols_data)
    write_mql5_symbols(symbols_data)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
