    def _emit_canonical_value(
        self,
        lines: list[str],
        value_expr: str,
        schema: dict[str, Any],
        source_file: str,
        indent: str,
        prefix: str,
    ) -> None:
        schema = resolve_ref(schema, self.schemas, source_file)
        if "oneOf" in schema:
            non_null = [item for item in schema["oneOf"] if item.get("type") != "null"]
            lines.append(f"{indent}if({value_expr} != NULL && {value_expr}.type == FARM_JSON_NULL)")
            lines.append(f'{indent}   return "null";')
            self._emit_canonical_value(
                lines,
                value_expr,
                non_null[0] if non_null else {"type": "null"},
                source_file,
                indent,
                prefix,
            )
            return
        schema_type = schema.get("type")
        if isinstance(schema_type, list):
            non_null = [item for item in schema_type if item != "null"]
            lines.append(f"{indent}if({value_expr} != NULL && {value_expr}.type == FARM_JSON_NULL)")
            lines.append(f'{indent}   return "null";')
            self._emit_canonical_value(
                lines,
                value_expr,
                {**schema, "type": non_null[0] if non_null else "null"},
                source_file,
                indent,
                prefix,
            )
            return
        if schema_type == "integer":
            lines.append(f"{indent}return FarmJsonCanonicalNumber({value_expr}, true);")
            return
        if schema_type == "number":
            lines.append(f"{indent}return FarmJsonCanonicalNumber({value_expr}, false);")
            return
        if schema_type == "array":
            item_schema = schema.get("items", {})
            lines.extend([f'{indent}string out = "[";', f"{indent}if({value_expr} != NULL)"])
            lines.append(f"{indent}{{")
            lines.append(f"{indent}   for(int i = 0; i < {value_expr}.Size(); i++)")
            lines.append(f"{indent}   {{")
            lines.append(f"{indent}      if(i > 0) out += \",\";")
            self._emit_append_canonical_value(
                lines,
                f"{value_expr}.At(i)",
                item_schema,
                source_file,
                indent + "      ",
                f"{prefix}_item",
            )
            lines.append(f"{indent}   }}")
            lines.append(f"{indent}}}")
            lines.append(f'{indent}return out + "]";')
            return
        if schema_type == "object":
            properties = schema.get("properties", {})
            additional = schema.get("additionalProperties")
            if not properties and isinstance(additional, dict):
                self._emit_dynamic_object(
                    lines,
                    value_expr,
                    additional,
                    source_file,
                    indent,
                    prefix,
                )
                return
            required = list(schema.get("required", []))
            names = [name for name in required if name in properties]
            names.extend(sorted(name for name in properties if name not in required))
            lines.extend([f'{indent}string out = "{{";', f"{indent}bool first = true;"])
            for index, name in enumerate(names):
                child = f"{prefix}_{index}"
                lines.append(f'{indent}CFarmJsonValue *{child} = {value_expr}.Get("{name}");')
                lines.append(f"{indent}if({child} != NULL)")
                lines.append(f"{indent}{{")
                lines.append(f'{indent}   FarmJsonAppendFieldPrefix(out, first, "{name}");')
                self._emit_append_canonical_value(
                    lines, child, properties[name], source_file, indent + "   ", child
                )
                lines.append(f"{indent}}}")
            lines.append(f'{indent}return out + "}}";')
            return
        lines.append(f"{indent}return FarmJsonCanonicalValue({value_expr});")

