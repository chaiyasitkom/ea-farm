@dataclass(frozen=True)
class FieldSpec:
    name: str
    annotation: str
    required: bool
    comment: str | None


@dataclass
class ClassSpec:
    name: str
    schema: dict[str, Any]
    fields: list[FieldSpec]
    comment: str | None
    extra: str


class PythonGenerator:
    def __init__(self, schemas: dict[str, dict[str, Any]]) -> None:
        self.schemas = schemas
        self.classes: OrderedDict[str, ClassSpec] = OrderedDict()
        self.enums: OrderedDict[str, list[Any]] = OrderedDict()

    def generate(self) -> str:
        self._add_common_classes()
        for name in PAYLOAD_FILES:
            self._add_object(
                self._payload_class_name(name), self.schemas[f"{name}.json"], f"{name}.json"
            )
        self._add_object("FarmEnvelope", self.schemas["envelope.json"], "envelope.json")

        lines = [*HEADER]
        lines.extend(
            [
                "from __future__ import annotations",
                "",
                "from enum import Enum",
                "from typing import Annotated, Any, Dict, List, Literal, Optional",
                "",
                "from pydantic import BaseModel, ConfigDict, Field",
                "",
                "",
            ]
        )

        for enum_name, values in self.enums.items():
            lines.append(f"class {enum_name}(str, Enum):")
            for value in values:
                if value is None:
                    continue
                lines.append(f"    {self._enum_member(str(value))} = {value!r}")
            lines.append("")
            lines.append("")

        for cls in self.classes.values():
            if cls.comment:
                lines.append("# INVARIANT (must be validated outside generated schema models):")
                for line in cls.comment.splitlines():
                    lines.append(f"#   {line}")
            lines.append(f"class {cls.name}(BaseModel):")
            lines.append(f'    model_config = ConfigDict(extra="{cls.extra}")')
            lines.append("")
            if not cls.fields:
                lines.append("    pass")
            for field in cls.fields:
                if field.comment:
                    for line in field.comment.splitlines():
                        lines.append(f"    # {line}")
                default = "" if field.required else " = None"
                lines.append(f"    {field.name}: {field.annotation}{default}")
            lines.append("")
            lines.append("")

        lines.append("PAYLOAD_MODELS: Dict[str, type[BaseModel]] = {")
        for msg_type in self.schemas["envelope.json"]["properties"]["type"]["enum"]:
            lines.append(f"    {msg_type!r}: {TYPE_TO_PAYLOAD[msg_type]},")
        lines.append("}")
        lines.append("")
        for class_name in self.classes:
            lines.append(f"{class_name}.model_rebuild()")
        lines.append("")
        return "\n".join(lines).rstrip() + "\n"

    def public_symbols(self) -> list[str]:
        return ["PAYLOAD_MODELS", *sorted([*self.enums.keys(), *self.classes.keys()])]

    def _add_common_classes(self) -> None:
        defs = self.schemas["common.json"]["$defs"]
        for name in ["account_info", "symbol_spec", "broker_time_info", "local_limits"]:
            self._add_object(self._class_name(name), defs[name], "common.json")

    def _add_object(self, class_name: str, schema: dict[str, Any], source_file: str) -> str:
        if class_name in self.classes:
            return class_name
        required = list(schema.get("required", []))
        properties = schema.get("properties", {})
        ordered_names = [name for name in required if name in properties]
        ordered_names.extend(sorted(name for name in properties if name not in required))

        fields: list[FieldSpec] = []
        self.classes[class_name] = ClassSpec(
            name=class_name,
            schema=schema,
            fields=fields,
            comment=schema.get("$comment"),
            extra="forbid" if class_name == "ConfigUpdateSettings" else "ignore",
        )
        for field_name in ordered_names:
            field_schema = properties[field_name]
            annotation = self._annotation(
                field_schema, f"{class_name}{self._class_name(field_name)}", source_file
            )
            if field_name == "payload" and class_name == "FarmEnvelope":
                annotation = "Dict[str, Any]"
            if field_name not in required:
                annotation = self._optional_annotation(annotation)
            if not field_name.isidentifier():
                raise ValueError(f"unsupported field name: {field_name}")
            fields.append(
                FieldSpec(
                    name=field_name,
                    annotation=annotation,
                    required=field_name in required,
                    comment=field_schema.get("description"),
                )
            )
        return class_name

    def _annotation(self, schema: dict[str, Any], name_hint: str, source_file: str) -> str:
        resolved = self._resolve_ref(schema, source_file)
        if "oneOf" in resolved:
            non_null = [item for item in resolved["oneOf"] if item.get("type") != "null"]
            has_null = len(non_null) != len(resolved["oneOf"])
            if len(non_null) != 1 or not has_null:
                raise ValueError(f"unsupported oneOf in {name_hint}")
            return f"Optional[{self._annotation(non_null[0], name_hint, source_file)}]"
        if "const" in resolved:
            return f"Literal[{resolved['const']!r}]"
        if "enum" in resolved:
            values = list(resolved["enum"])
            has_null = None in values
            enum_values = [value for value in values if value is not None]
            enum_name = self._enum_name(name_hint)
            if enum_name not in self.enums:
                self.enums[enum_name] = enum_values
            return f"Optional[{enum_name}]" if has_null else enum_name

        schema_type = resolved.get("type")
        if isinstance(schema_type, list):
            non_null_types = [item for item in schema_type if item != "null"]
            if len(non_null_types) != 1:
                raise ValueError(f"unsupported union type in {name_hint}: {schema_type}")
            inner = dict(resolved)
            inner["type"] = non_null_types[0]
            return f"Optional[{self._annotation(inner, name_hint, source_file)}]"
        if schema_type == "string":
            return self._annotated_scalar("str", resolved)
        if schema_type == "integer":
            return self._annotated_scalar("int", resolved)
        if schema_type == "number":
            return self._annotated_scalar("float", resolved)
        if schema_type == "boolean":
            return "bool"
        if schema_type == "array":
            return f"List[{self._annotation(resolved['items'], name_hint + 'Item', source_file)}]"
        if schema_type == "object":
            properties = resolved.get("properties")
            if properties:
                object_name = (
                    "ConfigUpdateSettings"
                    if name_hint == "ConfigUpdatePayloadSettings"
                    else name_hint
                )
                return self._add_object(object_name, resolved, source_file)
            additional = resolved.get("additionalProperties")
            if isinstance(additional, dict):
                value_type = self._annotation(additional, name_hint + "Value", source_file)
            else:
                value_type = "Any"
            key_type = "str"
            property_names = resolved.get("propertyNames")
            if isinstance(property_names, dict):
                key_type = self._annotation(property_names, name_hint + "Key", source_file)
            return f"Dict[{key_type}, {value_type}]"
        raise ValueError(f"unsupported schema in {name_hint}: {resolved}")

    def _resolve_ref(self, schema: dict[str, Any], source_file: str) -> dict[str, Any]:
        if "$ref" not in schema:
            return schema
        ref = schema["$ref"]
        filename, _, pointer = ref.partition("#/")
        if not filename:
            filename = source_file
        target: Any = self.schemas[filename]
        for part in pointer.split("/"):
            target = target[part]
        merged = dict(target)
        for key, value in schema.items():
            if key != "$ref":
                merged[key] = value
        return merged

    def _annotated_scalar(self, base: str, schema: dict[str, Any]) -> str:
        args: list[str] = []
        mapping = {
            "minimum": "ge",
            "maximum": "le",
            "exclusiveMinimum": "gt",
            "exclusiveMaximum": "lt",
            "minLength": "min_length",
            "maxLength": "max_length",
            "pattern": "pattern",
        }
        for src, dst in mapping.items():
            if src in schema:
                args.append(f"{dst}={schema[src]!r}")
        if not args:
            return base
        return f"Annotated[{base}, Field({', '.join(args)})]"

    @staticmethod
    def _optional_annotation(annotation: str) -> str:
        if annotation.startswith("Optional["):
            return annotation
        return f"Optional[{annotation}]"

    @staticmethod
    def _class_name(raw: str) -> str:
        return "".join(part.capitalize() for part in re.split(r"[^A-Za-z0-9]+", raw) if part)

    @staticmethod
    def _payload_class_name(raw: str) -> str:
        return PythonGenerator._class_name(raw) + "Payload"

    @staticmethod
    def _enum_name(raw: str) -> str:
        if raw.endswith("Enum"):
            return raw
        return raw + "Enum"

    @staticmethod
    def _enum_member(value: str) -> str:
        name = re.sub(r"[^A-Za-z0-9]+", "_", value).upper().strip("_")
        if not name or name[0].isdigit():
            name = "V_" + name
        return name


